// A PDF reader leaves a blank line after every line of text.
export const asPdfText = text => text.split('\n').join('\n\n');

// Mirrors extractText in site/admin/docx.js, which is how the browser reads an
// uploaded .docx, so a test can read the site's own template back without a
// DOM. Paragraph per line; a side-by-side role table splits into its columns;
// a two-column row prints as "label:\tvalue"; any other row joins its cells.
export function docxText(xml) {
  const root = {name: '#root', children: []}, stack = [root];
  for (const token of xml.matchAll(/<\?[^>]*\?>|<!--[\s\S]*?-->|<\/([\w:.-]+)\s*>|<([\w:.-]+)((?:\s+[\w:.-]+="[^"]*")*)\s*(\/?)>|([^<]+)/g)) {
    const [, close, open, , selfClosing, text] = token;
    if (close) { if (stack.length > 1) stack.pop(); }
    else if (open) { const node = {name: open, children: []}; stack[stack.length - 1].children.push(node); if (!selfClosing) stack.push(node); }
    else if (text) stack[stack.length - 1].children.push({name: '#text', text: text.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&#(\d+);/g, (_, code) => String.fromCodePoint(Number(code))).replace(/&amp;/g, '&')});
  }
  const descendants = (node, name, out = []) => { for (const child of node.children || []) { if (child.name === name) out.push(child); descendants(child, name, out); } return out; };
  const textOf = node => {
    let text = '';
    const walk = element => {
      if (element.name === 'w:del' || element.name === 'w:moveFrom') return;
      if (element.name === 'w:t') { text += (element.children || []).map(child => child.text || '').join(''); return; }
      if (element.name === 'w:tab') { text += '\t'; return; }
      if (element.name === 'w:br' || element.name === 'w:cr') { text += '\n'; return; }
      for (const child of element.children || []) walk(child);
    };
    walk(node); return text.trim();
  };
  const paragraphs = node => descendants(node, 'w:p').map(textOf).join('\n');
  const body = descendants(root, 'w:body')[0], lines = [];
  for (const node of body.children) {
    if (node.name === 'w:tbl') {
      const rows = node.children.filter(n => n.name === 'w:tr').map(row => row.children.filter(n => n.name === 'w:tc').map(paragraphs));
      const headers = rows[0] || [];
      if (headers.length > 1 && headers.every(h => h.length < 140 && /^(?:property manager|management|landlord|owner|lessor|tenant)\b/i.test(h))) {
        headers.forEach((heading, i) => { lines.push(heading + ':'); for (const row of rows.slice(1)) lines.push(row[i] || ''); lines.push(''); });
      } else for (const row of rows) {
        if (row.length === 2 && !row[0].includes('\n')) lines.push(row[0].replace(/[:：]$/, '') + ':\t' + row[1]);
        else lines.push(row.join('\n'));
      }
    } else if (node.name === 'w:p') lines.push(textOf(node));
    else if (node.name !== '#text') lines.push(paragraphs(node));
  }
  return lines.join('\n');
}
