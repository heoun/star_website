import assert from 'node:assert/strict';
import { selectQueueCases } from '../site/admin/case-queue-state.js';
const manager={role:'manager',email:'admin@example.test'}, agent={role:'agent',email:'a@example.test'};
const row=(id,bucket,since,responsible_email,status='new',collaborator_emails=[])=>({id,name:`Applicant ${id}`,status,responsible_email,collaborator_emails,listings:{property_name:'Parkside',unit:id},next_step:{bucket,since}});
const cases=[row('waiting','waiting','2026-01-01','a@example.test','sent_to_landlord'),row('action','attention','2026-02-01','a@example.test'),row('unassigned','attention','2026-03-01',null),row('shared','attention','2026-02-02','b@example.test','new',['a@example.test']),row('closed','closed','2025-01-01',null,'declined')];
const initial=JSON.stringify(cases), all={bucket:'all',stage:'',person:'',query:''};
const ids=(view,session=manager)=>selectQueueCases(cases,{...all,...view},session).map(row=>row.id);
assert.deepEqual(ids({}),['unassigned','action','shared','waiting','closed']);
assert.deepEqual(ids({bucket:'waiting',stage:'review'}),[],'Stage filters must not silently reset the queue tab');
assert.deepEqual(ids({person:'unassigned'}),['unassigned','closed']);
assert.deepEqual(ids({person:'a@example.test'}),['action','waiting']);
assert.deepEqual(ids({person:'lead'},agent),['action','waiting']);
assert.deepEqual(ids({person:'collaborating'},agent),['shared']);
assert.deepEqual(ids({query:'PARKSIDE action'}),['action'],'Property and unit search is case-insensitive');
assert.deepEqual(ids({query:'Applicant action'}),['action']);
assert.deepEqual(ids({bucket:'waiting'}),['waiting']);
assert.deepEqual(ids({stage:'closed'}),['closed']);
assert.equal(JSON.stringify(cases),initial,'Sorting never mutates the API response');
assert.deepEqual(selectQueueCases([],all,agent),[]);
console.log('PASS 12 queue checks: combined filters, responsibility/collaboration, priority, closed cases, search and immutable results');
